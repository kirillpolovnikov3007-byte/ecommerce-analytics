/*
Проект: Анализ данных интернет-магазина
Раздел: Анализ поведения клиентов

Цель:
Изучить частоту покупок и определить,
какая доля клиентов совершает повторные заказы.

Период исследования: 2021–2025 годы.

Гипотеза:
Большинство клиентов совершает
более одного заказа за период наблюдения.

Метрики:
1. Количество уникальных клиентов.
2. Количество клиентов с повторными покупками.
3. Repeat Purchase Rate.
4. Распределение клиентов по количеству заказов.
*/

WITH customer_orders AS (
    SELECT
        customer_id,
        COUNT(*) AS order_count
    FROM raw.orders
    GROUP BY customer_id
)
SELECT
    COUNT(*) AS total_customers,
    COUNT(*) FILTER (
        WHERE order_count >= 2
    ) AS repeat_customers,
    ROUND(
        COUNT(*) FILTER (WHERE order_count >= 2) * 100.0
        / NULLIF(COUNT(*), 0),
        2
    ) AS repeat_customer_rate
FROM customer_orders;
/*
РЕЗУЛЬТАТЫ ИССЛЕДОВАНИЯ

1. Всего уникальных клиентов — 24 911.

2. Повторные покупки совершили 24 387 клиентов.

3. Repeat Purchase Rate за 2021–2025 годы
   составляет 97,90%.

4. Самая многочисленная группа —
   клиенты с пятью заказами (4 288 человек).

5. Только 524 клиента совершили один заказ.

ВЫВОД

Гипотеза подтвердилась:
большинство клиентов совершает повторные покупки
в течение периода наблюдения.

Однако высокий Repeat Purchase Rate
не означает, что клиенты регулярно
возвращаются каждый месяц.

Для изучения возвращаемости во времени
дополнительно проведён когортный анализ.

БИЗНЕС-РЕКОМЕНДАЦИИ

1. Исследовать интервалы между покупками.
2. Выделить сегменты клиентов по частоте заказов.
3. Изучить поведение клиентов с одним заказом.
4. Проверить гипотезы по увеличению
   частоты повторных покупок.

ОГРАНИЧЕНИЯ

Метрики рассчитаны за весь пятилетний период.
Они не отражают частоту покупок внутри
отдельных месяцев и не учитывают покупки
до начала наблюдения.
*/